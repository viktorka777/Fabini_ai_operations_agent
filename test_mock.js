const fs = require('fs');
const assert = require('assert');
const AsyncFunction = Object.getPrototypeOf(async function(){}).constructor;
const state = {};
async function call(body) {
  const code=fs.readFileSync(__dirname+'/mock_api.js','utf8');
  const fn=new AsyncFunction('$input','$getWorkflowStaticData',code);
  return (await fn({first:()=>({json:{body}})},()=>state))[0].json;
}
(async()=>{
 let r=await call({tool:'create_ticket',order_id:'100245',description:'Unverified',run_id:'unverified'});
 assert.equal(r.payload.error,'order_not_verified');
 r=await call({tool:'get_order',order_id:'100245',run_id:'t1'});
 assert.equal(r.payload.status,'paid');
 r=await call({tool:'get_order',order_id:'100245',run_id:'t1'});
 assert.equal(r.payload.error,'duplicate_tool_call');
 r=await call({tool:'get_order',order_id:'100246',run_id:'t1'});
 assert.equal(r.payload.error,'order_scope_mismatch');
 for(const tool of ['get_payment','get_fulfillment','get_sync_logs'])await call({tool,order_id:'100245',run_id:'t1'});
 r=await call({tool:'retry_sync',order_id:'100245',run_id:'t1'});
 assert.equal(r.payload.status,'approval_required');
 const id=r.payload.proposal.id;
 assert.equal(state.orders['100245'].fulfillment.status,'not_received');
 r=await call({tool:'execute_approved',proposal_id:id,decision:'approve',lock_granted:false});
 assert.equal(r.status,403);
 r=await call({tool:'execute_approved',proposal_id:id,decision:'approve',lock_granted:true});
 assert.equal(r.payload.status,'completed');
 assert.equal(r.payload.verification.result.status,'ready_to_ship');
 assert.equal(r.payload.verification.result.shipped,false);
 r=await call({tool:'execute_approved',proposal_id:id,decision:'approve',lock_granted:true});
 assert.equal(r.status,409);
 for(const tool of ['get_order','get_payment','get_fulfillment','get_sync_logs'])await call({tool,order_id:'100246',run_id:'t2'});
 r=await call({tool:'retry_sync',order_id:'100246',run_id:'t2'});
 assert.equal(r.payload.error,'retry_not_applicable');
 r=await call({tool:'get_sync_logs',order_id:'100247',run_id:'t3'});
 assert.equal(r.payload.error,'wms_unavailable');
 r=await call({tool:'get_order',order_id:'999999',run_id:'t4'});
 assert.equal(r.status,404);
 for(const run_id of ['t5','t6','t7'])await call({tool:'get_order',order_id:'100246',run_id});
 r=await call({tool:'create_ticket',order_id:'100246',description:'Platba nebyla dokončena.',run_id:'t5'});
 const deny=r.payload.proposal.id;
 r=await call({tool:'execute_approved',proposal_id:deny,decision:'deny',lock_granted:true});
 assert.equal(r.payload.status,'denied');
 assert.equal(state.tickets.length,0);
 r=await call({tool:'create_ticket',order_id:'100246',description:'Ověřit platbu.',run_id:'t6'});
 const ticket=r.payload.proposal.id;
 r=await call({tool:'execute_approved',proposal_id:ticket,decision:'approve',lock_granted:true});
 assert.equal(r.payload.action_result.ticket_id,state.tickets[0].ticket_id);
 assert.equal(r.payload.verification.verified,true);
 r=await call({tool:'create_ticket',order_id:'100246',description:'Expired.',run_id:'t7'});
 state.proposals[r.payload.proposal.id].expires_at=0;
 r=await call({tool:'inspect_proposal',proposal_id:r.payload.proposal.id,decision:'approve'});
 assert.equal(r.status,410);
 console.log('PASS: mock tools, duplicate protection, approval, replay, denial, ticket verification, errors and expiry');
})().catch(e=>{console.error(e);process.exit(1);});
